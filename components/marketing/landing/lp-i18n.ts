/** Translates one text string of the landing page (Uzbek = the original). */
export function lpT(text: string, lang: Lang): string {
  if (lang === 'uz') return text
  const table = lang === 'ru' ? RU : EN
  return table[text] ?? translate(text, lang)
}

/** Translates all text segments of the static landing markup (works on server and client alike). */
export function translateHtml(html: string, lang: Lang): string {
  if (lang === 'uz') return html
  const table = lang === 'ru' ? RU : EN
  return html.replace(/>([^<>]+)</g, (m, seg: string) => {
    const tr = table[seg.replace(/\s+/g, ' ').trim()]
    if (!tr) return m
    const lead = /^\s*/.exec(seg)![0]
    const trail = /\s*$/.exec(seg)![0]
    return '>' + lead + tr + trail + '<'
  })
}
